#!/usr/bin/env node
// Fetches 30 days of MTR AFD issuance times from the NWS API and bakes the
// computed probability distribution directly into js/issuance-predictor.js.
// Run: node scripts/analyze-issuance.js

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT_FILE = path.join(__dirname, '..', 'js', 'issuance-predictor.js');

const WFO = 'MTR';
const TIMEZONE = 'America/Los_Angeles';
const SAMPLE_DAYS = 30;
const HEADERS = { 'User-Agent': 'synoptic-skies/1.0 (joshhuneycutt@gmail.com)' };

async function fetchAllProducts() {
  const products = [];
  let url = `https://api.weather.gov/products/types/AFD/locations/${WFO}`;

  while (url) {
    const res = await fetch(url, { headers: HEADERS });
    if (!res.ok) throw new Error(`NWS API ${res.status}: ${url}`);
    const data = await res.json();
    products.push(...(data['@graph'] ?? []));
    url = data['@pagination']?.next ?? null;

    // Stop once we have well beyond 30 days of coverage
    if (products.length >= 200) break;
  }
  return products;
}

function toPackificHour(isoString) {
  const date = new Date(isoString);
  const hour = parseInt(
    new Intl.DateTimeFormat('en-US', { hour: 'numeric', hour12: false, timeZone: TIMEZONE })
      .format(date),
    10
  );
  return hour === 24 ? 0 : hour;
}

function cutoffDate() {
  const d = new Date();
  d.setDate(d.getDate() - SAMPLE_DAYS);
  d.setHours(0, 0, 0, 0);
  return d;
}

function findPeakWindows(hourlyProb) {
  const HIGH = 0.18;
  const LOW  = 0.07;
  const LABELS = [
    [0,  5,  'Late night'],
    [5,  9,  'Early morning'],
    [9,  12, 'Morning'],
    [12, 17, 'Afternoon'],
    [17, 22, 'Evening'],
    [22, 24, 'Night'],
  ];

  function labelFor(startHour) {
    for (const [s, e, lbl] of LABELS) {
      if (startHour >= s && startHour < e) return lbl;
    }
    return 'Night';
  }

  const windows = [];
  let inWindow = false;
  let start = 0;

  for (let h = 0; h <= 23; h++) {
    const prob = hourlyProb[h];
    if (!inWindow && prob >= HIGH) {
      inWindow = true;
      start = h;
    } else if (inWindow && prob < LOW) {
      windows.push({ startHour: start, endHour: h - 1, label: labelFor(start),
        probability: Math.max(...hourlyProb.slice(start, h)) });
      inWindow = false;
    }
  }
  if (inWindow) {
    windows.push({ startHour: start, endHour: 23, label: labelFor(start),
      probability: Math.max(...hourlyProb.slice(start)) });
  }
  return windows;
}

async function main() {
  console.log(`Fetching AFD issuance history for ${WFO}...`);
  const all = await fetchAllProducts();

  const cutoff = cutoffDate();
  const recent = all.filter(p => new Date(p.issuanceTime) >= cutoff);
  console.log(`  ${all.length} total products fetched, ${recent.length} within last ${SAMPLE_DAYS} days`);

  const counts = new Array(24).fill(0);
  for (const p of recent) counts[toPackificHour(p.issuanceTime)]++;

  const hourlyProbability = counts.map((count, hour) => ({
    hour,
    count,
    probability: parseFloat((count / SAMPLE_DAYS).toFixed(3)),
  }));

  const peakWindows = findPeakWindows(hourlyProbability.map(h => h.probability));
  console.log(`  Peak windows found: ${peakWindows.map(w => w.label).join(', ')}`);

  const data = {
    wfo: WFO,
    generatedAt: new Date().toISOString(),
    sampleDays: SAMPLE_DAYS,
    sampleCount: recent.length,
    hourlyProbability,
    peakWindows,
    timezone: TIMEZONE,
  };

  // Read existing predictor file to preserve the logic section
  let existingLogic = '';
  if (fs.existsSync(OUT_FILE)) {
    const existing = fs.readFileSync(OUT_FILE, 'utf8');
    const marker = '// --- PREDICTOR LOGIC (do not edit above this line) ---';
    const idx = existing.indexOf(marker);
    if (idx !== -1) existingLogic = existing.slice(idx);
  }

  const dataBlock = `// AUTO-GENERATED by scripts/analyze-issuance.js — do not edit manually
const ISSUANCE_DATA = ${JSON.stringify(data, null, 2)};

`;

  const logicBlock = existingLogic || `// --- PREDICTOR LOGIC (do not edit above this line) ---
export const IssuancePredictor = (() => {
  function getPacificHour() {
    const now = new Date();
    const h = parseInt(
      new Intl.DateTimeFormat('en-US', { hour: 'numeric', hour12: false, timeZone: ISSUANCE_DATA.timezone })
        .format(now), 10
    );
    return h === 24 ? 0 : h;
  }

  function getNextExpected(lastIssuedAt) {
    const lastMs  = lastIssuedAt instanceof Date ? lastIssuedAt.getTime() : new Date(lastIssuedAt).getTime();
    const nowMs   = Date.now();
    const ageHrs  = (nowMs - lastMs) / 3_600_000;

    if (ageHrs < 1) return { state: 'just_issued' };

    const currentHour = getPacificHour();
    const windows = ISSUANCE_DATA.peakWindows;

    // Check if we're currently inside a peak window
    for (const w of windows) {
      if (currentHour >= w.startHour && currentHour <= w.endHour) {
        return { state: 'in_window', ...w };
      }
    }

    // Find next upcoming window today, then tomorrow
    for (const w of windows) {
      if (w.startHour > currentHour) {
        return { state: 'next_window', hoursUntil: w.startHour - currentHour, ...w };
      }
    }
    // Wrap to first window tomorrow
    const first = windows[0];
    if (first) {
      return { state: 'next_window', hoursUntil: (24 - currentHour) + first.startHour, ...first };
    }
    return null;
  }

  function formatWindow(startHour, endHour) {
    function fmt(h) {
      if (h === 0)  return 'midnight';
      if (h === 12) return 'noon';
      const ampm = h < 12 ? 'AM' : 'PM';
      const h12  = h % 12 || 12;
      return \`\${h12} \${ampm}\`;
    }
    return \`~\${fmt(startHour)}–\${fmt(endHour)}\`;
  }

  return {
    getNextExpected,
    formatWindow,
    getHourlyProbabilities: () => ISSUANCE_DATA.hourlyProbability,
    getPeakWindows:          () => ISSUANCE_DATA.peakWindows,
    getMeta:                 () => ({ wfo: ISSUANCE_DATA.wfo, generatedAt: ISSUANCE_DATA.generatedAt,
                                      sampleDays: ISSUANCE_DATA.sampleDays, sampleCount: ISSUANCE_DATA.sampleCount }),
  };
})();
`;

  fs.writeFileSync(OUT_FILE, dataBlock + logicBlock, 'utf8');
  console.log(`Written to ${OUT_FILE}`);
  console.log(`  Sample: ${data.sampleCount} AFDs over ${data.sampleDays} days`);
}

main().catch(err => { console.error(err); process.exit(1); });
